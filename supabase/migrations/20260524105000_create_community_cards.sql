create table public.community_cards (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  image_url text,
  button_text text not null,
  button_url text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
grant select on table public.community_cards to anon, authenticated;
grant insert, update, delete on table public.community_cards to authenticated;
grant usage, select on sequence public.community_cards_id_seq to authenticated;
alter table public.community_cards enable row level security;
drop policy if exists "Allow public read access to active community cards" on public.community_cards;
create policy "Allow public read access to active community cards"
on public.community_cards
for select
to anon, authenticated
using (is_active = true);
drop policy if exists "Authenticated users can manage community cards" on public.community_cards;
create policy "Authenticated users can manage community cards"
on public.community_cards
for all
to authenticated
using (true)
with check (true);
